// Reproducible terrain sampling, not a weather-station or mid-elevation claim.
import { readFile, writeFile } from 'node:fs/promises';
import { resorts } from '../js/resorts.js';
import { TRAIL_CATALOG } from '../js/trail-catalog.js';
import { mountainSlug } from '../js/mountain-config.js';

const locations = {};
for (const resort of resorts) {
  const terrain = TRAIL_CATALOG[mountainSlug(resort.name)];
  if (!terrain) throw new Error(`Missing terrain: ${resort.name}`);
  const data = JSON.parse(await readFile(new URL(`../data/trails/${terrain.file}`, import.meta.url)));
  const trails = data.features.filter(f => f.properties.kind === 'trail' && f.geometry.type === 'LineString' && f.geometry.coordinates.length > 1);
  if (!trails.length) throw new Error(`No trail sampling points: ${resort.name}`);
  // One midpoint per mapped trail segment avoids overweighting densely digitized paths.
  const candidates = trails.map(f => ({ feature:f, point:f.geometry.coordinates[Math.floor(f.geometry.coordinates.length / 2)] }));
  const median = values => values.sort((a,b) => a-b)[Math.floor(values.length/2)];
  const center = [median(candidates.map(c => c.point[0])), median(candidates.map(c => c.point[1]))];
  const distance = p => ((p[0]-center[0])*Math.cos(center[1]*Math.PI/180))**2+(p[1]-center[1])**2;
  candidates.sort((a,b) => distance(a.point)-distance(b.point));
  const { point, feature } = candidates[0];
  locations[resort.name] = { lat:point[1], lon:point[0], label:'Mapped ski terrain', method:'trail-spatial-median', terrainFile:terrain.file, featureId:feature.properties.id, featureName:feature.properties.name || 'Unnamed trail', sourceUrl:`https://openskimap.org/#15/${point[1]}/${point[0]}`, elevationM:null };
  if (resort.name === 'Whistler Blackcomb') {
    const gondola = data.features.find(f => f.properties.id === 32774598);
    if (!gondola) throw new Error('Whistler PEAK 2 PEAK geometry missing.');
    const [lon,lat] = gondola.geometry.coordinates[0];
    Object.assign(locations[resort.name], {lat,lon,label:'Roundhouse / PEAK 2 PEAK',method:'official-elevation',featureId:32774598,featureName:gondola.properties.name,elevationM:1850,sourceUrl:'https://www.whistlerblackcomb.com/the-mountain/mountain-conditions/snow-and-weather-report'});
  }
}
await writeFile(new URL('../js/weather-locations-data.js', import.meta.url), `// Generated by scripts/build_weather_locations.mjs. Terrain samples, not observations.\nexport const WEATHER_LOCATIONS = ${JSON.stringify(locations,null,2)};\n`);
console.log(`Generated ${Object.keys(locations).length} terrain weather locations.`);
